/**
 * 线性降级:没被任何结构类认领的元素。
 *
 * 原则:**绝不吞内容** —— 能转的子节点照转,认不出的自己留一个可见标记,
 * 让模型知道"这里有一点我没完全读懂",而不是以为公式就这么短。
 */
import { M as 公式ns } from '../../ooxml/ns.js'
import { 公式结构 } from '../structure.js'

export class 线性降级 extends 公式结构 {
  转 (节点, 上下文) {
    const 子文本 = 上下文.子们(节点)
    if (子文本.trim()) return 子文本
    // 完全没内容且不是属性节点:留标记
    return `[未解析:${节点.前缀 ? 节点.前缀 + ':' : ''}${节点.名}]`
  }
}
