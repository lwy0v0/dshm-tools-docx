/**
 * manifest.json:产物自己的"身份证明"。
 *
 * 作用只有一个:**下次调用能判断这份产物还能不能用**(源文件指纹 + 转换器版本 + 选项)。
 */

export const 产物版本 = 3
export const 转换器名 = 'dshm-tools-docx'

/**
 * @returns {object}
 */
export function 生成清单 ({
  源文件, 源大小, 源mtime, sha256, 产物根, 转换时间,
  统计, 不可得, 章节, 资源, 文档属性, 选项, 规范化 = null, 版本
}) {
  return {
    产物版本,
    转换器: `${转换器名}@${版本}`,
    转换时间,
    源: {
      路径: 源文件,
      大小: 源大小,
      mtime: 源mtime,
      sha256
    },
    // 原生 docx 为 null;非 docx 输入记下"怎么转过来的",便于事后判断可信度
    规范化: 规范化
      ? {
          原始格式: 规范化.原始格式,
          引擎: 规范化.引擎,
          策略: 规范化.策略,
          后端: 规范化.后端,
          中间文件: 规范化.中间文件,
          缺失字体: 规范化.缺失字体 || [],
          ...(规范化.PDF分类 ? { PDF分类: 规范化.PDF分类 } : {}),
          ...(规范化.公式图 ? { 公式图: 规范化.公式图 } : {}),
          ...(规范化.公式OCR ? { 公式OCR: 规范化.公式OCR } : {})
        }
      : null,
    产物: {
      根: 产物根,
      索引: 'index.md',
      全文: 'content.md',
      章节目录: 'chapters',
      媒体目录: 'media',
      章节: 章节.map(c => ({ 标题: c.标题, 文件: c.文件名, 行数: c.行.length }))
    },
    统计,
    不可得,
    选项,
    文档属性,
    资源: {
      图片: 资源.图片.map(x => ({ 路径: x.相对路径, 宽: x.宽, 高: x.高, 类型: x.类型, 替代文字: x.替代文字 })),
      公式数: 资源.公式.length,
      图表数: 资源.图表.length,
      表格数: 资源.表格.length,
      书签: 资源.书签
    }
  }
}

/** 缓存命中判断 */
export function 可用 (旧清单, { sha256, 版本, 选项 }) {
  if (!旧清单) return false
  if (旧清单.产物版本 !== 产物版本) return false
  if (旧清单.转换器 !== `${转换器名}@${版本}`) return false
  if (旧清单.源?.sha256 !== sha256) return false
  if (!!旧清单.选项?.导出图片 !== !!选项.导出图片) return false
  if (!!旧清单.选项?.带样式 !== !!选项.带样式) return false
  // 换了 PDF 解析器就不能复用旧产物(两者产出的 docx 完全不同)
  if ((旧清单.选项?.解析器 || '') !== (选项.解析器 || '')) return false
  return true
}
